import assert from "node:assert/strict";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";
import { EXACT_ROUTE_SOURCE_OWNERS } from "./renderer-route-recovery.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const releaseRoot = path.join(root, ".reference/app-original/webview/assets");
const owners = [
  {
    directory: "mark-session-create",
    output: "mark-session-create-6f7d531b2a15.js",
    expectedExports: 69,
    markers: [
      "startup_connection_timeout_threshold_millis",
      "web_enabled",
      "surfaceToStart.start()",
      "session.reset()",
      "allowOverride",
    ],
  },
  {
    directory: "realtime-voice-controls-surface",
    output: "controls-fedbfda05b6b.js",
    expectedExports: 41,
    markers: [
      "--codex-pet-width",
      "activity-primary",
      "voice-microphone",
      "voice-output",
      "avatarOverlay.quickChatBar.restore",
    ],
  },
];

function exportNames(source) {
  return [...source.matchAll(/export\s*\{([\s\S]*?)\};/g)]
    .flatMap((match) => match[1].split(","))
    .map((entry) => entry.trim().match(/(?:\bas\s+)?([\w$]+)$/)?.[1])
    .filter(Boolean)
    .sort();
}

let assertions = 0;
const equal = (actual, expected, message) => {
  assert.deepEqual(actual, expected, message);
  assertions += 1;
};
const check = (value, message) => {
  assert.ok(value, message);
  assertions += 1;
};

equal(EXACT_ROUTE_SOURCE_OWNERS.size, 0, "no exact route owner remains");

for (const owner of owners) {
  const directory = path.join(root, "src/renderer", owner.directory);
  const entry = path.join(directory, "index.ts");
  const source = await fs.readFile(entry, "utf8");
  await assert.rejects(
    fs.stat(path.join(directory, "exact.js")),
    (error) => error?.code === "ENOENT",
    `${owner.directory} no longer has an exact.js fallback`,
  );
  assertions += 1;
  check(source.includes("Recovered TypeScript owner"), `${owner.directory} identifies its recovered owner`);
  check(!source.includes("Generated by scripts/promote-exact"), `${owner.directory} is not a promoted exact owner`);
  for (const marker of owner.markers) {
    check(source.includes(marker), `${owner.directory} retains ${marker}`);
  }

  const result = await esbuild.build({
    entryPoints: [entry],
    bundle: true,
    format: "esm",
    platform: "browser",
    target: "esnext",
    write: false,
    logLevel: "silent",
    plugins: [
      {
        name: "voice-owner-externals",
        setup(build) {
          build.onResolve({ filter: /^@(?:exact-chunk|rchunk)\// }, ({ path: dependency }) => ({
            path: dependency.replace(/^@(?:exact-chunk|rchunk)\//, "./"),
            external: true,
          }));
        },
      },
    ],
  });
  const compiledExports = exportNames(result.outputFiles[0].text);
  const releaseExports = exportNames(await fs.readFile(path.join(releaseRoot, owner.output), "utf8"));
  equal(compiledExports, releaseExports, `${owner.directory} preserves the release ABI`);
  equal(compiledExports.length, owner.expectedExports, `${owner.directory} export count`);
}

console.log(`${assertions} realtime voice owner contract assertions passed`);
