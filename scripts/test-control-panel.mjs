import assert from "node:assert/strict";
import { Buffer } from "node:buffer";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(ROOT, "src/renderer/control-panel/index.ts");
const source = fs.readFileSync(sourcePath, "utf8");
const calls = { jsxInit: 0, katexInit: 0, katexProps: [] };
const node = (type, props) => typeof type === "function" ? type(props) : { type, props };
globalThis.__controlPanel = { calls, node };
const result = await esbuild.build({ entryPoints: [sourcePath], bundle: true, format: "esm", platform: "node", target: "node22", write: false, logLevel: "silent", plugins: [{ name: "mocks", setup(build) {
  build.onResolve({ filter: /^@rchunk\// }, ({ path: importPath }) => ({ path: importPath.slice(8), namespace: "mock" }));
  build.onLoad({ filter: /.*/, namespace: "mock" }, ({ path: module }) => {
    if (module === "app-shared") return { contents: "const s=globalThis.__controlPanel;export const I3=()=>({jsx:s.node,jsxs:s.node});export const h4=()=>{s.calls.jsxInit++};export const m4=(...v)=>v.filter(Boolean).join(' ');", loader: "js" };
    if (module === "learning-block-katex") return { contents: "const s=globalThis.__controlPanel;export const n=()=>{s.calls.katexInit++};export const t=props=>{s.calls.katexProps.push(props);return {type:'katex',props}};", loader: "js" };
    return { contents: "export {};", loader: "js" };
  });
} }] });
const module = await import("data:text/javascript;base64," + Buffer.from(result.outputFiles[0].text).toString("base64"));
let assertions = 0;
const equal = (actual, expected) => { assertions++; assert.equal(actual, expected); };
const deepEqual = (actual, expected) => { assertions++; assert.deepEqual(actual, expected); };
deepEqual(Object.keys(module), ["a", "i", "n", "r", "t"]);
equal(/\bany\b/.test(source), false);
equal(/import \* as/.test(source), false);
deepEqual([...source.matchAll(/(?:from )?"@rchunk\/([^"]+)"/g)].map((match) => match[1]), ["rolldown-runtime", "app-shared", "learning-block-katex"]);
module.a();
module.a();
equal(calls.jsxInit, 1);
equal(calls.katexInit, 1);
const control = module.r({ children: "controls", screenReaderContent: "screen reader" });
equal(control.type, "div");
equal(control.props.children[0], "controls");
equal(control.props.children[1].props.className, "sr-only");
const captionPanel = module.t({ children: "caption", reserveLines: 2 });
equal(captionPanel.props.className.includes("min-h-10"), true);
deepEqual(captionPanel.props.children, ["caption", null]);
equal(module.n({ content: null }), null);
equal(module.n({ content: false }), null);
const title = module.n({ content: "fallback", children: "chosen", variant: "title" });
equal(title.props.className.includes("text-base"), true);
equal(title.props.children.props.children.props.children, "chosen");
const katex = module.n({ content: "x^2", format: "katex" });
equal(katex.props.children.props.children.props.children.type, "katex");
deepEqual(calls.katexProps, [{ latex: "x^2" }]);
const divider = module.i();
equal(divider.type, "div");
equal(divider.props.className.includes("border-t"), true);
console.log("control-panel tests passed (" + assertions + " assertions)");
