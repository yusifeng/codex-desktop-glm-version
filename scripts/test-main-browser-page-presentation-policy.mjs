import assert from "node:assert/strict";
import fs from "node:fs";
import { build } from "esbuild";

let assertions = 0;
const equal = (actual, expected, message) => { assert.deepEqual(actual, expected, message); assertions += 1; };
const output = await build({ entryPoints: [new URL("../src/main/main-app/browser-sidebar/browser-page-presentation-policy.ts", import.meta.url).pathname], bundle: true, format: "esm", platform: "node", target: "node22", write: false });
const { createBrowserPagePresentationPolicy } = await import(`data:text/javascript;base64,${Buffer.from(output.outputFiles[0].text).toString("base64")}`);
const policy = createBrowserPagePresentationPolicy({ isFirstPartyUrl: (url) => url.startsWith("https://first.test"), pageUrl: (page) => page.url });

equal(policy.securityStateForPage({ loadError: { errorDescription: "ERR_CERT_DATE_INVALID" } }), "certificate-error");
equal(policy.securityStateForPage({ loadError: { errorDescription: "ERR_CONNECTION_RESET" } }), null);
equal(policy.securityStateForPage({ loadError: null }), null);

const throttling = [];
let captured = false;
const webContents = { isDestroyed: () => false, isBeingCaptured: () => captured, setBackgroundThrottling: (value) => throttling.push(value) };
let showInactive = 0;
let windowDestroyed = false;
let windowVisible = true;
const windowState = { window: { isDestroyed: () => windowDestroyed, isVisible: () => windowVisible, showInactive: () => { showInactive += 1; } } };
const thread = { page: { url: "https://first.test/page", view: { webContents } }, visible: false, isBrowserUseActive: false };
policy.syncBackgroundThrottling(windowState, thread);
equal(throttling, [true]);
equal(showInactive, 0);
thread.visible = true;
policy.syncBackgroundThrottling(windowState, thread);
equal(throttling, [true, false]);
equal(showInactive, 1);
policy.syncBackgroundThrottling(windowState, thread);
equal(showInactive, 1);
thread.visible = false;
captured = true;
policy.syncBackgroundThrottling(windowState, thread);
equal(throttling.at(-1), false);
captured = false;
thread.isBrowserUseActive = true;
policy.syncBackgroundThrottling(windowState, thread);
equal(throttling.at(-1), false);
policy.syncBackgroundThrottling(windowState, thread, "https://external.test");
equal(throttling.at(-1), true);
thread.visible = true;
policy.syncBackgroundThrottling(windowState, thread);
equal(showInactive, 2);
windowVisible = false;
policy.syncBackgroundThrottling(windowState, thread, "https://external.test");
policy.syncBackgroundThrottling(windowState, thread);
equal(showInactive, 2);
windowVisible = true;
windowDestroyed = true;
policy.syncBackgroundThrottling(windowState, thread, "https://external.test");
policy.syncBackgroundThrottling(windowState, thread);
equal(showInactive, 2);

policy.syncBackgroundThrottling(windowState, { page: null });
equal(throttling.length > 0, true);
const main = fs.readFileSync(new URL("../.reference/originals/main/main-C-Mhak1n.ts", import.meta.url), "utf8");
equal(main.includes('require("./main-app/browser-sidebar/browser-page-presentation-policy.js")'), true);
for (const oldOwner of ["function oZe(", "function sZe(", "function lZ(", "function cZe(", "function dZe(", "function dZ("]) equal(main.includes(oldOwner), false);
equal(main.includes("syncBackgroundThrottling: dZ"), true);
equal(main.includes("createBrowserPageMaterializationControllerClass"), true);
console.log(`${assertions} main browser page presentation policy assertions passed`);
