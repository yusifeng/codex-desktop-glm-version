import assert from "node:assert/strict";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const { DynamicAppToolPendingResponses } = require("../app/.vite/build/main-app/app-server/dynamic-app-tool-pending-responses.js");
const router = new DynamicAppToolPendingResponses({ safeParse(value) { return value?.ok ? { success: true, data: value.value } : { success: false, error: "invalid" }; } });
const pending = router.wait("x");
assert.throws(() => router.wait("x"), /pending/);
assert.equal(router.route({ id: "x", result: { ok: true, value: 7 } }), true);
assert.equal(await pending, 7);
assert.equal(router.route({ id: "x", result: { ok: true, value: 8 } }), false);
const canceled = router.wait("y");
router.cancel("y");
await assert.rejects(canceled, /cancelled/);
const failed = router.wait("error");
assert.equal(router.route({ id: "error", error: { message: "bad" } }), true);
await assert.rejects(failed, /bad/);
const invalid = router.wait("invalid");
assert.equal(router.route({ id: "invalid", result: { ok: false } }), true);
await assert.rejects(invalid, /invalid response/);
const disposed = router.wait("z");
router.dispose();
await assert.rejects(disposed, /disposed/);
const fallbackRouter = new DynamicAppToolPendingResponses(() => undefined);
const fallbackPending = fallbackRouter.wait("fallback");
assert.equal(fallbackRouter.route({ id: "fallback", result: { contentItems: [{ type: "inputText", text: "ok" }], success: true } }), true);
assert.deepEqual(await fallbackPending, { contentItems: [{ type: "inputText", text: "ok" }], success: true });
const fallbackInvalid = fallbackRouter.wait("fallback-invalid");
assert.equal(fallbackRouter.route({ id: "fallback-invalid", result: { contentItems: [{ type: "inputText" }], success: true } }), true);
await assert.rejects(fallbackInvalid, /invalid response/);
console.log("11 dynamic app-tool pending-response assertions passed");
