import assert from "node:assert/strict";
import path from "node:path";
import { createRequire } from "node:module";
import * as esbuild from "esbuild";
import os from "node:os";
import fs from "node:fs/promises";
const dir = await fs.mkdtemp(path.join(os.tmpdir(), "codex-live-abort-policy-")); const output = path.join(dir, "policy.cjs");
await esbuild.build({ entryPoints: ["src/main/worker/git-live-query-policy.ts"], outfile: output, bundle: true, format: "cjs", platform: "node", target: "esnext", logLevel: "silent" });
const { shouldAbortSharedRun } = createRequire(import.meta.url)(output);
assert.equal(shouldAbortSharedRun(0), true); assert.equal(shouldAbortSharedRun(-1), true); assert.equal(shouldAbortSharedRun(1), false); assert.equal(shouldAbortSharedRun(2), false);
console.log("worker Git live query abort policy tests passed (4 assertions)");
