import assert from "node:assert/strict";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const { createAnnotationSurfaceRegistryState } = require("../app/.vite/build/browser-page-preload/annotation-surface-registry-state.js");

const state = createAnnotationSurfaceRegistryState();
const first = {};
const second = {};
const record = { id: "surface-1", customRendering: true };
assert.equal(state.disposed, false);
assert.equal(state.hasSurface(first), false);
assert.equal(state.setSurface(first, record), undefined);
assert.equal(state.hasSurface(first), true);
assert.equal(state.getSurface(first), record);
assert.equal(state.surfaceCount(), 1);
assert.equal(state.wasProbed(second), false);
state.markProbed(second);
assert.equal(state.wasProbed(second), true);
assert.equal(state.nextRequestId("request"), "request-1");
assert.equal(state.nextRequestId("request"), "request-2");
const pending = { element: first, registrationId: "surface-1", requestId: "request-1", point: { x: 1, y: 2 }, surfaceRect: { x: 0, y: 0, width: 10, height: 10 }, timer: setTimeout(() => {}, 1000), finish() {} };
state.pending = pending;
assert.equal(state.pending, pending);
assert.equal(state.dispose(), true);
clearTimeout(pending.timer);
assert.equal(state.dispose(), false);
assert.equal(state.disposed, true);
assert.equal(state.hasSurface(first), false);
assert.equal(state.getSurface(first), undefined);
assert.equal(state.surfaceCount(), 0);
assert.equal(state.pending, null);
assert.equal(state.nextRequestId("late"), undefined);
assert.equal(state.setSurface(first, record), undefined);
assert.equal(state.deleteSurface(first), false);
console.log("16 preload annotation surface registry state assertions passed");
