import assert from "node:assert/strict";
import { isGlobalBareOrUnsupported, isGlobalDictationWatchable, normalizeGlobalAccelerator, remapGlobalShortcutForLayout, resolveMacModifierNames, resolveWin32ModifierGroups, splitGlobalAccelerator, validateGlobalShortcut } from "../app/.vite/build/main-app/hotkey/global-shortcut-policy.js";

const isBareModifierAccelerator = (value, platform) => platform === "darwin" && value.toLowerCase() === "fn";
const isBareOrUnsupported = (value) => value.toLowerCase() === "shift";
const deps = { isBareModifierAccelerator, isBareOrUnsupported };
let assertions = 0;
const check = (actual, expected) => { assert.equal(actual, expected); assertions += 1; };
check(validateGlobalShortcut("", "win32", deps), "Shortcut cannot be empty.");
check(validateGlobalShortcut("Ctrl+K", "win32", deps), null);
check(validateGlobalShortcut("K", "win32", deps), "Shortcut must include Cmd/Ctrl or Alt.");
check(validateGlobalShortcut("Ctrl+K+L", "win32", deps), "Shortcut must include exactly one non-modifier key.");
check(validateGlobalShortcut("Shift", "win32", deps), "Choose a shortcut with Ctrl or Alt plus another key.");
check(validateGlobalShortcut("Fn", "darwin", deps), null);
check(remapGlobalShortcutForLayout("CmdOrCtrl+Q", { KeyQ: "a" }), "CmdOrCtrl+Q");
check(remapGlobalShortcutForLayout("CmdOrCtrl+A", { KeyQ: "a" }), "CmdOrCtrl+Q");
check(remapGlobalShortcutForLayout("Ctrl+1", { Digit2: "1" }), "Ctrl+2");
check(isGlobalDictationWatchable("Command", "darwin", { macModifierNames: () => ["command"], win32KeyGroups: () => null }), true);
check(isGlobalDictationWatchable("Ctrl", "win32", { macModifierNames: () => [], win32KeyGroups: () => [[17]] }), true);
check(isGlobalDictationWatchable("Ctrl", "linux", { macModifierNames: () => [], win32KeyGroups: () => null }), false);
assert.deepEqual(resolveMacModifierNames("CmdOrCtrl+Alt+Shift+cmd"), ["command", "alternate", "shift"]); assertions += 1;
assert.deepEqual(resolveMacModifierNames("Control+Option+Unknown"), ["control", "alternate"]); assertions += 1;
assert.deepEqual(resolveWin32ModifierGroups("Ctrl+Alt", "win32"), [[17], [18]]); assertions += 1;
assert.equal(resolveWin32ModifierGroups("Ctrl", "linux"), null); assertions += 1;
assert.equal(normalizeGlobalAccelerator(" Ctrl-Shift_A "), "ctrlshifta"); assertions += 1;
assert.deepEqual(splitGlobalAccelerator(" Ctrl + + K "), ["Ctrl", "K"]); assertions += 1;
assert.equal(isGlobalBareOrUnsupported("left_shift", () => null), true); assertions += 1;
assert.equal(isGlobalBareOrUnsupported("Ctrl", () => "Ctrl"), true); assertions += 1;
console.log(`main global shortcut policy assertions passed (${assertions})`);
