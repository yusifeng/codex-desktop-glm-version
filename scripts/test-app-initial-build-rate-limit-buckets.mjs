import assert from "node:assert/strict";
import esbuild from "esbuild";
const sourcePath = new URL("../src/renderer/app-initial/runtime/build-rate-limit-buckets.ts", import.meta.url).pathname;
const built = await esbuild.build({ entryPoints: [sourcePath], bundle: true, format: "esm", platform: "node", target: "node22", write: false, logLevel: "silent" });
const mod = await import(`data:text/javascript;base64,${Buffer.from(built.outputFiles[0].text).toString("base64")}`);
const entry = { limitName: "core", snapshot: { primary: { windowDurationMins: 60 }, secondary: { windowDurationMins: 60 } } };
const buckets = mod.buildRateLimitBuckets(entry, "core", Boolean, (bucket, role, index) => `${role}-${bucket.windowDurationMins}-${index}`);
assert.equal(buckets.length, 2);
assert.equal(buckets[0].key, "core-primary-60-0");
assert.equal(buckets[1].limitName, "core");
console.log("app-initial build rate-limit buckets: 3 assertions passed");
