import assert from "node:assert/strict";
import esbuild from "esbuild";
const sourcePath = new URL("../src/renderer/app-primary/runtime/has-displayable-action.ts", import.meta.url).pathname;
const built = await esbuild.build({ entryPoints: [sourcePath], bundle: true, format: "esm", platform: "node", target: "node22", write: false, logLevel: "silent" });
const { hasDisplayableAction } = await import(`data:text/javascript;base64,${Buffer.from(built.outputFiles[0].text).toString("base64")}`);
assert.equal(hasDisplayableAction({ text: "Run" }), true);
assert.equal(hasDisplayableAction({ action_v2: { action_enum: "copy_to_clipboard", text: "Copy" } }), true);
assert.equal(hasDisplayableAction({ id: "action-id" }), true);
assert.equal(hasDisplayableAction({ text: "   ", id: "" }), false);
console.log("app-primary has displayable action: 4 assertions passed");
