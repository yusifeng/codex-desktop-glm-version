import assert from "node:assert/strict";
import path from "node:path";
import { createRequire } from "node:module";
import * as esbuild from "esbuild";
import os from "node:os";
import fs from "node:fs/promises";
const dir = await fs.mkdtemp(path.join(os.tmpdir(), "codex-git-node-policy-"));
const output = path.join(dir, "policy.cjs");
await esbuild.build({ entryPoints: ["src/main/worker/git-node-request-policy.ts"], outfile: output, bundle: true, format: "cjs", platform: "node", target: "esnext", logLevel: "silent" });
const { isGitNodeRequestMethod } = createRequire(import.meta.url)(output);
for (const method of ["github-request", "automation-writable-roots", "read-git-file-binary", "prepare-worktree-snapshot"]) assert.equal(isGitNodeRequestMethod(method), true);
assert.equal(isGitNodeRequestMethod("status-summary"), false);
console.log("worker Git node request policy tests passed (5 assertions)");
