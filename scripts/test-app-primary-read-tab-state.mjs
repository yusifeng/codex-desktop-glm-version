import assert from "node:assert/strict";
import esbuild from "esbuild";
const sourcePath = new URL("../src/renderer/app-primary/runtime/read-tab-state.ts", import.meta.url).pathname;
const built = await esbuild.build({ entryPoints: [sourcePath], bundle: true, format: "esm", platform: "node", target: "node22", write: false, logLevel: "silent" });
const mod = await import(`data:text/javascript;base64,${Buffer.from(built.outputFiles[0].text).toString("base64")}`);
const reader = { get: (_namespace, key) => key === "tab\0browser" ? { open: true } : null };
assert.deepEqual(mod.readTabState(reader, "ns", "tab", "browser"), { open: true });
assert.equal(mod.readTabState(reader, "ns", null, "browser"), null);
assert.equal(mod.readTabState(reader, "ns", "tab", undefined), null);
console.log("app-primary read tab state: 3 assertions passed");
