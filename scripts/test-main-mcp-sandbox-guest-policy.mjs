import assert from "node:assert/strict";
import { transform } from "esbuild";
import vm from "node:vm";
import { readFile } from "node:fs/promises";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const source = await readFile(new URL("../src/main/sandbox-preload/sandbox-guest-policy.ts", import.meta.url), "utf8");
const compiled = await transform(source, { loader: "ts", format: "cjs", platform: "node" });
const module = { exports: {} };
vm.runInNewContext(compiled.code, { module, exports: module.exports, require, URL, URLSearchParams });
const p = module.exports;
assert.equal(p.getTargetOrigin("https://foo.web-sandbox.oaiusercontent.com/?app=skybridge#initId=abc"), "https://foo.web-sandbox.oaiusercontent.com");
assert.equal(p.getTargetOrigin("https://foo.web-sandbox.oaiusercontent.com/?app=skybridge", { requireSkybridge: true }), "https://foo.web-sandbox.oaiusercontent.com");
assert.equal(p.getTargetOrigin("https://foo.web-sandbox.oaiusercontent.com/other?app=skybridge", { requireSkybridge: true }), null);
assert.equal(p.validateSandboxUrl("https://user:pass@web-sandbox.oaiusercontent.com/"), null);
assert.equal(p.validateSandboxUrl("https://web-sandbox.oaiusercontent.com:444/"), null);
assert.equal(p.validateSandboxUrl("https://evil.example/"), null);
assert.equal(p.extractInitId("https://web-sandbox.oaiusercontent.com/#initId=abc_DEF-123"), "abc_DEF-123");
assert.equal(p.extractInitId("https://web-sandbox.oaiusercontent.com/#initId=bad.value"), null);
assert.equal(p.extractInitId("https://web-sandbox.oaiusercontent.com/"), null);
assert.equal(p.REQUIRED_PORT_NAMES.length, 12);
assert.equal(p.ALL_ALLOWED_PORT_NAMES.length, 17);
console.log("main MCP sandbox guest policy: 10 assertions passed");
