import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = path.join(ROOT, ".reference/app-original/webview/assets/browser-6350a2274cdd.js");
const OUTPUT = path.join(ROOT, "src/renderer/symbol-browser/emoji-data.generated.ts");

function extractObjectLiteral(source, assignment) {
  const assignmentIndex = source.indexOf(assignment);
  if (assignmentIndex < 0) throw new Error("Unable to find " + assignment);
  const start = source.indexOf("{", assignmentIndex + assignment.length);
  let depth = 0;
  let quote = null;
  let escaped = false;
  for (let index = start; index < source.length; index += 1) {
    const character = source[index];
    if (quote != null) {
      if (escaped) escaped = false;
      else if (character === "\\") escaped = true;
      else if (character === quote) quote = null;
      continue;
    }
    if (character === "'" || character === '"' || character === "\u0060") {
      quote = character;
      continue;
    }
    if (character === "{") depth += 1;
    else if (character === "}") {
      depth -= 1;
      if (depth === 0) return source.slice(start, index + 1);
    }
  }
  throw new Error("Unterminated object literal for " + assignment);
}

const source = fs.readFileSync(SOURCE, "utf8");
const data = vm.runInNewContext("(" + extractObjectLiteral(source, "He=") + ")", Object.create(null), { timeout: 2_000 });
const categoryNames = {
  activities: "Activities",
  animals_nature: "Animals & Nature",
  flags: "Flags",
  food_drink: "Food & Drink",
  objects: "Objects",
  symbols: "Symbols",
  travel_places: "Travel & Places",
};
const peopleStart = data.emojis.smileys_people.findIndex((entry) => entry.u === "1f44b");
const entries = Object.entries(data.emojis).flatMap(([categoryId, categoryEntries]) => categoryEntries.map((entry, index) => {
  const emoji = String.fromCodePoint(...entry.u.split("-").map((value) => Number.parseInt(value, 16)))
    .replace(/(\p{Emoji_Presentation})\uFE0F/gu, "$1");
  const category = categoryId === "smileys_people"
    ? index < peopleStart ? "Smileys & Emotion" : "People & Body"
    : categoryNames[categoryId];
  return category == null ? null : {
    category,
    emoji,
    keywords: entry.n.map((keyword) => keyword.toLowerCase()),
    name: entry.n.at(-1).toLowerCase(),
  };
})).filter(Boolean);

const generated = [
  "// Generated by scripts/generate-symbol-browser-emoji-data.mjs from the published Unicode catalog.",
  "// Do not edit this file manually.",
  "export interface EmojiCatalogEntry {",
  "  category: string;",
  "  emoji: string;",
  "  keywords: readonly string[];",
  "  name: string;",
  "}",
  "export const EMOJI_CATALOG: readonly EmojiCatalogEntry[] = " + JSON.stringify(entries) + ";",
  "",
].join("\n");
fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
fs.writeFileSync(OUTPUT, generated);
console.log("generated " + entries.length + " emoji catalog entries");
