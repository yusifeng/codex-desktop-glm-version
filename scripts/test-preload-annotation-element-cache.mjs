import assert from "node:assert/strict";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const { createAnnotationElementCacheRegistry } = require("../app/.vite/build/browser-page-preload/annotation-element-cache.js");
const registry = createAnnotationElementCacheRegistry();
const hostA = {}, hostB = {};
const cacheA = registry.get(hostA);
assert.equal(registry.get(hostA), cacheA);
assert.notEqual(registry.get(hostB), cacheA);
cacheA.set("annotation", { node: true });
assert.equal(cacheA.size, 1);
registry.dispose();
assert.equal(cacheA.size, 0);
assert.equal(registry.disposed, true);
const afterDispose = registry.get(hostA);
assert.notEqual(afterDispose, cacheA);
afterDispose.set("late", true);
assert.equal(afterDispose.size, 1);
registry.dispose();
assert.equal(afterDispose.size, 1);
console.log("test-preload-annotation-element-cache: 9 assertions passed");
