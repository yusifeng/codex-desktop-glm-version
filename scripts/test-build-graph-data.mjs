import assert from "node:assert/strict";
import { Buffer } from "node:buffer";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(ROOT, "src/renderer/build-graph-data/index.ts");
const source = fs.readFileSync(sourcePath, "utf8");
const result = await esbuild.build({ entryPoints: [sourcePath], bundle: true, format: "esm", platform: "node", target: "node22", write: false, logLevel: "silent", plugins: [{ name: "graph-data-mocks", setup(build) { build.onResolve({ filter: /^@rchunk\// }, ({ path: importPath }) => ({ path: importPath.slice(8), namespace: "mock" })); build.onLoad({ filter: /.*/, namespace: "mock" }, () => ({ contents: "export {};", loader: "js" })); } }] });
const module = await import("data:text/javascript;base64," + Buffer.from(result.outputFiles[0].text).toString("base64"));
assert.deepEqual(Object.keys(module), ["a", "c", "i", "l", "n", "o", "r", "s", "t", "u"]);
assert.equal(/\bany\b/.test(source), false);
assert.deepEqual([...source.matchAll(/import\s+(?:[^;]*?from\s*)?"@rchunk\/([^"]+)"/g)].map((match) => match[1]), ["rolldown-runtime", "linear"]);
module.a();
assert.deepEqual(module.o, { width: 360, height: 220, padding: 0 });
assert.deepEqual(module.s, { width: 360, height: 360, padding: 0 });
assert.equal(module.l, 360);
assert.equal(module.c, 220);
const x = { type: "identifier", value: "x" };
const number = (value) => ({ type: "number", value });
const operator = (value) => ({ type: "operator", value });
const fn = (value) => ({ type: "function", value });
assert.equal(module.n([x, number(2), operator("*"), number(1), operator("+")], 3), 7);
assert.equal(module.n([number(-8), number(1), number(3), operator("/"), operator("^")], 0), -2);
assert.equal(module.n([number(2), fn("custom")], 0, {}, (name, value) => name === "custom" ? value * 5 : 0), 10);
assert.equal(module.i([x, number(2), operator("*"), fn("sin")]), Math.PI);
assert.equal(module.i([x, number(3), operator("*"), fn("tan")]), Math.PI / 3);
const hints = module.r([number(1), x, number(2), operator("-"), operator("/")], {}, -5, 5);
assert.deepEqual(hints.explicitPoleXs, [2]);
assert.deepEqual(hints.knownPoleXs, [2]);
const line = module.t([x], {}, { xDomain: [-2, 2] });
assert.deepEqual(line.xDomain, [-2, 2]);
assert.equal(line.segments.length, 1);
assert.equal(line.paths.length, 1);
assert.equal(line.paths[0].startsWith("M 0 "), true);
assert.equal(line.paths[0].includes("L 360 "), true);
const reciprocal = module.t([number(1), x, operator("/")], {}, { xDomain: [-1, 1], yDomain: [-10, 10] }, module.o, { discontinuityMode: "interactive" });
assert.equal(reciprocal.segments.length >= 2, true);
assert.throws(() => module.t([x], {}, undefined, module.o, { maxEvaluations: 599 }), /at least 600/);
assert.equal(module.t([number(Number.NaN)], {}), null);
console.log("build-graph-data tests passed (22 assertions)");
