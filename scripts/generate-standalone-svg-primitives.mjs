#!/usr/bin/env node
// 从发布版的独立 SVG chunk 生成语义化 renderer 模块。
// 这些 chunk 共享同一形态：延迟取得 JSX runtime，再导出一个 SVG 组件。

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SPECS = [
  ["arrow-curved-right", "arrow-curved-right-f88ac704e2f7.ts", "ArrowCurvedRightIcon"],
  ["arrow-rotate-ccw", "arrow-rotate-ccw-b6615005fd79.ts", "ArrowRotateCounterclockwiseIcon"],
  ["bar-chart-icon", "bar-chart-df721a832f82.ts", "BarChartIcon"],
  ["book-open", "book-open-49e6c579d8f3.ts", "BookOpenIcon"],
  ["document-search-icon", "document-search-d1a8a918aa84.ts", "DocumentSearchIcon"],
  ["file-blank-icon", "file-blank-b55ab355e982.ts", "FileBlankIcon"],
  ["filter", "filter-b13f62bf3469.ts", "FilterIcon"],
  ["filter-alt", "filter-alt-b31dfd74b521.ts", "FilterAltIcon"],
  ["filter-alt-badged", "filter-alt-badged-3f054bc3fda5.ts", "FilterAltBadgedIcon"],
  ["folder-light-icon", "folder-light-2f9486c690e0.ts", "FolderLightIcon"],
  ["hand-icon", "hand-ab2b3e50d560.ts", "HandIcon"],
  ["plus-sm-icon", "plus-sm-7f7ff2c8a312.ts", "PlusSmallIcon"],
  ["reddit-logo", "reddit-7cd517f2e808.ts", "RedditLogo"],
  ["security-keys", "security-keys-a34b7fb8f7ef.ts", "SecurityKeysIcon"],
  ["shield-check", "shield-check-cd8c69f429ca.ts", "ShieldCheckIcon"],
  ["text-shorter", "text-shorter-a76bbb7184d8.ts", "TextShorterIcon"],
  ["thumb-mixed", "thumb-mixed-e90a960095aa.ts", "ThumbMixedIcon"],
  ["twitter-logo", "twitter-4ec2d9a72253.ts", "TwitterLogo"],
  ["undo", "undo-56dd6481731f.ts", "UndoIcon"],
];

function extractCallExpression(source, start) {
  let depth = 0;
  let quote = null;
  let escaped = false;
  for (let index = start; index < source.length; index++) {
    const character = source[index];
    if (quote != null) {
      if (escaped) escaped = false;
      else if (character === "\\") escaped = true;
      else if (character === quote) quote = null;
      continue;
    }
    if (character === "`" || character === "\"" || character === "'") {
      quote = character;
      continue;
    }
    if (character === "(") depth++;
    else if (character === ")") {
      depth--;
      if (depth === 0) {
        const remainder = source.slice(index + 1);
        const next = remainder.match(/^\s*/)?.[0].length ?? 0;
        if (remainder[next] !== "(") return source.slice(start, index + 1);
      }
    }
  }
  throw new Error("Unbalanced standalone SVG expression");
}

for (const [directory, sourceFile, componentName] of SPECS) {
  const sourcePath = path.join(ROOT, "src/webview/assets", sourceFile);
  const source = fs.readFileSync(sourcePath, "utf8");
  const assignment = /\(\w+\s*=\s*\(e\)\s*=>\s*/.exec(source);
  if (assignment == null) throw new Error(`Cannot locate SVG component in ${sourceFile}`);
  const expressionStart = assignment.index + assignment[0].length;
  const expression = extractCallExpression(source, expressionStart)
    .replace(/\(0,\s*\w+\.jsx\)/g, "jsxRuntime.jsx")
    .replace(/\(0,\s*\w+\.jsxs\)/g, "jsxRuntime.jsxs")
    .replace(/\.\.\.e\b/g, "...props");
  const initializerName = `initialize${componentName}`;
  const output = `// Generated by scripts/generate-standalone-svg-primitives.mjs from ${sourceFile}.
// Keep the semantic component name and compatibility exports; regenerate to refresh SVG paths.

import { I3 as getJsxRuntime, e6 as initializeReactRuntime } from "@rchunk/app-shared";
import "@rchunk/rolldown-runtime";

export interface SvgIconProps extends Record<string, unknown> {
  className?: string;
}

let jsxRuntime: ReturnType<typeof getJsxRuntime> | undefined;
function ${componentName}(props: SvgIconProps): unknown {
  if (jsxRuntime == null) return null;
  return ${expression};
}

let initialized = false;
function ${initializerName}(): void {
  if (initialized) return;
  initialized = true;
  initializeReactRuntime();
  jsxRuntime = getJsxRuntime();
}

export { ${initializerName} as n, ${componentName} as t };
`;
  const outputDirectory = path.join(ROOT, "src/renderer", directory);
  fs.mkdirSync(outputDirectory, { recursive: true });
  fs.writeFileSync(path.join(outputDirectory, "index.ts"), output);
}

console.log(`generated ${SPECS.length} standalone SVG primitive modules`);
