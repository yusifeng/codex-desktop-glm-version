import assert from "node:assert/strict";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const { createAnnotationSerialization } = require("../app/.vite/build/browser-page-preload/annotation-serialization.js");
const limits = { maxSerializedBytes: 64, maxKeys: 2, maxKeyLength: 16, maxStringValueLength: 12 };
const safeString = (value) => ({ success: typeof value === "string" && value.length > 0 && value.length <= 12, data: value });
const safeKey = (value) => ({ success: typeof value === "string" && /^[A-Za-z][A-Za-z0-9_-]*$/.test(value) && value.length <= 16 });
const safeValue = (value) => ({ success: value == null || typeof value === "boolean" || (typeof value === "number" && Number.isFinite(value)) || (typeof value === "string" && value.length <= 12) });
const safeRecord = (value) => ({ success: value && typeof value === "object" && Object.entries(value).every(([key, item]) => safeKey(key).success && safeValue(item).success), data: value });
const serialization = createAnnotationSerialization({ getLimits: () => limits, parseName: safeString, parseKey: safeKey, parseValue: safeValue, parseMetadata: safeRecord, parseString: safeString });
assert.equal(serialization.normalizeName("button"), "button");
assert.equal(serialization.normalizeName(""), undefined);
assert.deepEqual(serialization.sanitizeMetadata({ source: "toolbar", enabled: true }), { source: "toolbar", enabled: true });
assert.equal(serialization.sanitizeMetadata({ "bad key!": true }), undefined);
assert.equal(serialization.sanitizeMetadata({ a: 1, b: 2, c: 3 }), undefined);
assert.equal(serialization.sanitizeMetadata(Object.create({ inherited: true })), undefined);
assert.deepEqual(serialization.parseMetadata('{"source":"toolbar"}'), { source: "toolbar" });
assert.equal(serialization.parseMetadata("x".repeat(65)), undefined);
assert.equal(serialization.parseMetadata("not-json"), undefined);
assert.equal(serialization.withinLimit("é".repeat(40)), false);
console.log("11 preload annotation serialization assertions passed");
