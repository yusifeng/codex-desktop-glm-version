import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(
  root,
  ".reference/app-original/webview/assets/command-messages-294d3e3133e1.js",
);
const destinationPath = path.join(
  root,
  "src/renderer/command-messages/catalog.generated.ts",
);
const source = await readFile(sourcePath, "utf8");
const descriptors = new Map();
const pattern = /id:`([^`]*)`,defaultMessage:`([^`]*)`,description:`([^`]*)`/g;

for (const match of source.matchAll(pattern)) {
  const [, id, defaultMessage, description] = match;
  const descriptor = { id, defaultMessage, description };
  const previous = descriptors.get(id);
  if (
    previous != null &&
    JSON.stringify(previous) !== JSON.stringify(descriptor)
  ) {
    throw new Error(`Conflicting command message descriptor: ${id}`);
  }
  descriptors.set(id, descriptor);
}

if (descriptors.size < 250) {
  throw new Error(
    `Expected at least 250 command descriptors, found ${descriptors.size}`,
  );
}

const entries = [...descriptors].sort(([left], [right]) =>
  left.localeCompare(right),
);
const output = [
  "// Generated by scripts/recover-command-message-catalog.mjs from the captured release chunk.",
  "// This checked-in catalog is runtime-independent; the release artifact is only a recovery input.",
  "export interface CommandMessageDescriptor {",
  "  defaultMessage: string;",
  "  description: string;",
  "  id: string;",
  "}",
  "",
  "export const commandMessageCatalog: Readonly<Record<string, CommandMessageDescriptor>> = {",
  ...entries.map(
    ([id, descriptor]) =>
      `  ${JSON.stringify(id)}: ${JSON.stringify(descriptor)},`,
  ),
  "};",
  "",
].join("\n");

await writeFile(destinationPath, output);
console.log(`Recovered ${descriptors.size} command message descriptors`);
