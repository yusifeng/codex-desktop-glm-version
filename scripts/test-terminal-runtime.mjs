import assert from "node:assert/strict";
import { Buffer } from "node:buffer";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
globalThis.__terminalRuntimeTest = { warning: { dismissedTarget: null, dismiss() {}, reset() {} } };
const result = await esbuild.build({ entryPoints: [path.join(ROOT, "src/renderer/runtime/index.ts")], bundle: true, format: "esm", platform: "node", target: "node22", write: false, logLevel: "silent", plugins: [{ name: "terminal-runtime-mocks", setup(build) { build.onResolve({ filter: /^@rchunk\// }, ({ path: importPath }) => ({ path: importPath.slice(8), namespace: "mock" })); build.onLoad({ filter: /.*/, namespace: "mock" }, ({ path: module }) => ({ contents: module === "terminal-workspace-warning-state" ? "export const r=globalThis.__terminalRuntimeTest.warning;export const t=()=>{};" : "export {};", loader: "js" })); } }] });
const terminal = await import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString("base64")}`);
assert.deepEqual(Object.keys(terminal), ["a", "c", "d", "f", "i", "l", "m", "n", "o", "p", "r", "s", "t", "u"]);
const tabEvents = [];
const scope = { route: { routeKind: "local-thread", conversationId: "conversation-1", cwd: "/work/project", hostId: "local" }, defaultTerminalLocation: "bottom", onTabsChanged(tabs) { tabEvents.push(tabs.map(tab => ({ ...tab }))); } };
assert.equal(terminal.t(scope), true);
assert.equal(terminal.l(scope), "bottom");
assert.equal(terminal.c(scope), false);
assert.equal(terminal.u(scope), false);
const first = terminal.r(scope);
assert.equal(first, "terminal-1");
assert.equal(terminal.d.getTabs(scope).length, 1);
assert.equal(terminal.d.getTabs(scope)[0].panel, "bottom");
assert.equal(terminal.d.getTabs(scope)[0].title, "project");
assert.equal(terminal.c(scope), true);
assert.equal(terminal.u(scope), false);
assert.equal(tabEvents.length, 1);
assert.equal(terminal.r(scope), first);
assert.equal(terminal.d.getTabs(scope).length, 1);
terminal.o(scope, "right");
assert.equal(terminal.d.getTabs(scope).length, 2);
assert.equal(terminal.d.getTabs(scope)[1].panel, "right");
assert.equal(terminal.d.getTabs(scope)[1].title, "project");
assert.equal(terminal.u(scope), true);
assert.equal(terminal.c(scope), false);
terminal.p(scope, "bottom");
assert.equal(terminal.c(scope), true);
assert.equal(terminal.d.getTabs(scope).length, 2);
terminal.i(scope, { panel: "right", sessionId: "restored", snapshot: { cwd: "/tmp/archive", title: "Build logs", exitCode: 0 } });
assert.equal(terminal.d.getTabs(scope).length, 3);
assert.equal(terminal.d.getTabs(scope)[2].title, "Build logs");
assert.equal(terminal.d.getTabs(scope)[2].panel, "right");
assert.equal(terminal.u(scope), false);
assert.equal((await terminal.d.preloadExisting(scope, "preloaded", { cwd: "/tmp/preload" }, "right")), true);
assert.equal(terminal.d.getTabs(scope).length, 4);
assert.equal(terminal.d.getTabs(scope)[3].title, "preload 3");
const closed = terminal.d.close(scope, "restored");
assert.equal(closed.title, "Build logs");
assert.equal(terminal.d.getTabs(scope).some(tab => tab.sessionId === "restored"), false);
terminal.o(scope, "bottom", first);
assert.equal(terminal.d.getTabs(scope).some(tab => tab.sessionId === first), false);
assert.equal(terminal.d.getTabs(scope).filter(tab => tab.panel === "bottom").length, 1);
const home = { route: { routeKind: "home", clientThreadId: "client-1", cwd: "C:\\repo\\app" }, locale: { formatMessage(_descriptor, values) { return `终端 ${values.index}`; } } };
assert.equal(terminal.t(home), true);
assert.equal(terminal.l(home), "right");
terminal.a(home);
assert.equal(terminal.d.getTabs(home)[0].panel, "bottom");
assert.equal(terminal.d.getTabs(home)[0].title, "app");
const untitled = { route: { routeKind: "home", clientThreadId: "client-2" }, locale: home.locale };
terminal.a(untitled);
assert.equal(terminal.d.getTabs(untitled)[0].title, "终端 1");
const unavailable = { route: { routeKind: "chatgpt-thread", conversationId: "cloud" } };
assert.equal(terminal.t(unavailable), false);
assert.equal(terminal.r(unavailable), null);
assert.equal(await terminal.d.preloadExisting(unavailable, "x", {}), false);
const disabled = { route: { routeKind: "local-thread", conversationId: "local" }, isTerminalDisabled: true };
assert.equal(terminal.t(disabled), false);
const automatic = { route: { routeKind: "local-thread", conversationId: "auto", cwd: "/auto" }, isWorkspaceReady: false };
terminal.s(automatic);
assert.equal(terminal.d.getTabs(automatic).length, 0);
automatic.isWorkspaceReady = true;
terminal.s(automatic);
assert.equal(terminal.d.getTabs(automatic).length, 1);
terminal.s(automatic);
assert.equal(terminal.d.getTabs(automatic).length, 1);
const watched = { route: { routeKind: "local-thread", conversationId: "watched" }, isWorkspaceReady: true };
const unwatch = terminal.m(watched);
assert.equal(terminal.d.getTabs(watched).length, 1);
assert.equal(typeof unwatch, "function");
unwatch();
assert.equal(terminal.n(), undefined);
const assertionCount = [...fs.readFileSync(fileURLToPath(import.meta.url), "utf8").matchAll(/\bassert\./g)].length;
console.log(`${assertionCount} terminal runtime assertions passed`);
