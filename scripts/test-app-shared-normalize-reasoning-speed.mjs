import assert from "node:assert/strict";
import esbuild from "esbuild";
const sourcePath = new URL("../src/renderer/app-shared/runtime/normalize-reasoning-speed.ts", import.meta.url).pathname;
const built = await esbuild.build({ entryPoints: [sourcePath], bundle: true, format: "esm", platform: "node", target: "node22", write: false, logLevel: "silent" });
const mod = await import(`data:text/javascript;base64,${Buffer.from(built.outputFiles[0].text).toString("base64")}`);
assert.equal(mod.normalizeReasoningSpeed("priority"), "fast");
assert.equal(mod.normalizeReasoningSpeed("balanced", " FAST "), "fast");
assert.equal(mod.normalizeReasoningSpeed("ultrafast"), "ultrafast");
assert.equal(mod.normalizeReasoningSpeed("slow"), null);
console.log("app-shared normalize reasoning speed: 4 assertions passed");
