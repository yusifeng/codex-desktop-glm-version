import assert from "node:assert/strict";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const { createAnnotationPreloadMessageQueueState } = require("../app/.vite/build/browser-page-preload/annotation-preload-message-queue-state.js");
const state = createAnnotationPreloadMessageQueueState();
assert.equal(state.destroyed, false);
assert.equal(state.mounted, false);
state.setMounted(true); state.setBufferedSync({ type: "sync" }); state.setPendingTextSelection(true); state.setPendingEditorMessage({ type: "edit" });
assert.equal(state.mounted, true);
assert.deepEqual(state.bufferedSync, { type: "sync" });
assert.equal(state.pendingTextSelection, true);
assert.deepEqual(state.pendingEditorMessage, { type: "edit" });
state.dispose();
assert.equal(state.destroyed, true);
assert.equal(state.mounted, false);
assert.equal(state.bufferedSync, null);
assert.equal(state.pendingTextSelection, false);
assert.equal(state.pendingEditorMessage, null);
console.log("test-preload-annotation-preload-message-queue-state: 10 assertions passed");
