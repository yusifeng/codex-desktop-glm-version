import assert from "node:assert/strict";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const policy = require("../app/.vite/build/worker/git-branch-search-policy.js");
let count = 0;
const eq = (a, b) => { count++; assert.equal(a, b); };
const deq = (a, b) => { count++; assert.deepEqual(a, b); };
eq(policy.normalizeGitBranchSearchText(" Feature/foo_bar.BAZ "), "feature foo bar baz");
eq(policy.normalizeGitBranchSearchText("---"), "");
deq(policy.buildGitBranchSearchRefPatterns("refs/heads", ["feature"]), ["refs/heads"]);
deq(policy.buildGitBranchSearchRefPatterns("refs/remotes", ["a", "!!"]), ["refs/remotes"]);
deq(policy.buildGitBranchSearchRefPatterns("refs/remotes", ["ab", "feature"]), ["refs/remotes/**/*[fF][eE][aA][tT][uU][rR][eE]*", "refs/remotes/**/*[fF][eE][aA][tT][uU][rR][eE]*/**"]);
deq(policy.buildGitBranchSearchRefPatterns("refs/remotes", ["ok"]), ["refs/remotes/**/*[oO][kKK]*", "refs/remotes/**/*[oO][kKK]*/**"]);
eq(policy.parseGitBranchSearchRef("refs/heads/feature/x", false), "feature/x");
eq(policy.parseGitBranchSearchRef("refs/remotes/origin/feature/x", false), "feature/x");
eq(policy.parseGitBranchSearchRef("refs/remotes/origin/feature/x", true), "refs/remotes/origin/feature/x");
eq(policy.parseGitBranchSearchRef("refs/remotes/origin/HEAD", false), null);
eq(policy.parseGitBranchSearchRef("refs/remotes/origin", false), null);
eq(policy.parseGitBranchSearchRef("refs/tags/v1", false), null);
eq(policy.stripGitRemoteRefPrefix("refs/remotes/upstream/topic"), "upstream/topic");
eq(policy.gitBranchNameFromRef("refs/remotes/upstream/topic/x"), "topic/x");
eq(policy.gitBranchNameFromRef("topic/x"), "topic/x");
console.log(`${count} worker git branch-search-policy assertions passed`);
