#!/usr/bin/env node

// 从官方 chunk 中机械提取内嵌 VGS Collect 表单。它本来就是一段独立 HTML/JS
// sandbox 程序；保持逐字符内容可避免语义重写误改支付字段或验证协议。

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(
  root,
  ".reference/app-original/webview/assets/wallet-onboarding-announcement-content-28d619ce7d4e.js",
);
const outputPath = path.join(
  root,
  "src/renderer/wallet-onboarding-announcement-content/wallet-enrollment-html.ts",
);
const source = fs.readFileSync(sourcePath, "utf8");
const start = source.indexOf("function De(");
const end = source.indexOf("}var U,W,G,K,q,J,Oe,Y,ke;", start);
if (start < 0 || end < 0)
  throw new Error("Unable to locate Wallet enrollment HTML template");

const functionSource = source
  .slice(start, end + 1)
  .replace(/^function De\(/, "export function buildWalletEnrollmentHtml(");
const prelude =
  `// @ts-nocheck\n// Generated by scripts/generate-wallet-enrollment-html.mjs. Do not hand-edit.\n` +
  `const U = "__wallet_onboarding_retry_bootstrap";\n` +
  `const W = "__wallet_onboarding_register_vgs_card";\n` +
  `const G = "__wallet_onboarding_request_verification";\n` +
  `const K = "__wallet_onboarding_verify_card";\n` +
  `const q = "__wallet_onboarding_finalize_card";\n` +
  `const J = "__wallet_onboarding_stage";\n` +
  `const Y = "https://js.verygoodvault.com/vgs-collect/3.2.2/vgs-collect.js";\n` +
  `const ke = 15_000;\n\n`;

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, `${prelude}${functionSource}\n`);
console.log(`generated ${path.relative(root, outputPath)}`);
