import assert from "node:assert/strict";
import fs from "node:fs/promises";
import * as esbuild from "esbuild";
const source = await fs.readFile("src/main/worker/terminal-open-policy.ts", "utf8");
const { code } = await esbuild.transform(source, { loader: "ts", format: "cjs" });
const module = { exports: {} }; new Function("module", "exports", code)(module, module.exports);
const { buildTerminalEditorArgs, buildMacTerminalLaunch } = module.exports;
assert.deepEqual(buildTerminalEditorArgs("nvim", { line: 4, column: 8 }), ["+call cursor(4,8)"]);
assert.deepEqual(buildTerminalEditorArgs("vim", { line: 1, column: 2 }), ["+call cursor(1,2)"]);
assert.deepEqual(buildTerminalEditorArgs("nano", { line: 12, column: 3 }), ["+12,3"]);
assert.deepEqual(buildTerminalEditorArgs("less", { line: 7, column: 1 }), ["+7g"]);
assert.deepEqual(buildTerminalEditorArgs("code", { line: 7, column: 1 }), []);
assert.deepEqual(buildTerminalEditorArgs("nvim", null), []);
assert.deepEqual(buildMacTerminalLaunch("kitty", "echo hi", "/bin/bash").args, ["-na", "kitty.app", "--args", "/bin/bash", "-lc", "echo hi"]);
assert.deepEqual(buildMacTerminalLaunch("ghostty", "echo hi").args, ["-na", "Ghostty.app", "--args", "-e", "/bin/zsh", "-lc", "echo hi"]);
assert.equal(buildMacTerminalLaunch("terminal", 'echo "hi"').args[1], 'tell application "Terminal" to do script "echo \\"hi\\""');
assert.match(buildMacTerminalLaunch("iterm2", "echo hi").args[1], /tell application "iTerm"/);
assert.equal(buildMacTerminalLaunch("unknown", "echo hi"), null);
console.log("worker terminal open policy tests passed (11 assertions)");
