import assert from "node:assert/strict";
import esbuild from "esbuild";
const sourcePath = new URL("../src/renderer/app-shared/runtime/derive-notification-status.ts", import.meta.url).pathname;
const built = await esbuild.build({ entryPoints: [sourcePath], bundle: true, format: "esm", platform: "node", target: "node22", write: false, logLevel: "silent" });
const { deriveNotificationStatus } = await import(`data:text/javascript;base64,${Buffer.from(built.outputFiles[0].text).toString("base64")}`);
assert.equal(deriveNotificationStatus(false, [{ level: "danger" }]), null);
assert.equal(deriveNotificationStatus(true, [{ level: "warning" }]), "attention");
assert.equal(deriveNotificationStatus(true, [{ level: "success" }]), "success");
assert.equal(deriveNotificationStatus(true, [{ kind: "first-awake", level: "success" }]), null);
console.log("app-shared derive notification status: 4 assertions passed");
