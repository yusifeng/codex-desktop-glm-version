import assert from "node:assert/strict";
import { Buffer } from "node:buffer";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const state = { initialized: 0, reducerCalls: [] };
globalThis.__legacyStudySchedule = state;
const result = await esbuild.build({ entryPoints: [path.join(ROOT, "src/renderer/legacy-study-hours-schedule/index.ts")], bundle: true, format: "esm", platform: "node", target: "node22", write: false, logLevel: "silent", plugins: [{ name: "legacy-study-schedule-mocks", setup(build) { build.onResolve({ filter: /^@rchunk\// }, ({ path: importPath }) => ({ path: importPath.slice(8), namespace: "mock" })); build.onLoad({ filter: /.*/, namespace: "mock" }, ({ path: module }) => ({ contents: module === "app-initial" ? ["const state=globalThis.__legacyStudySchedule;", "export const Mqt=()=>{state.initialized+=1};", "export const jqt=['mon','tue','wed','thu','fri','sat','sun'];", "export const Nqt=(current,action)=>{state.reducerCalls.push({current,action});if(action.type==='set_enabled')return {...current,enabled:action.enabled};if(action.type==='add_block')return {...current,blocks:[...current.blocks,{id:'added',days:['mon'],start_time:'09:00',end_time:'10:00'}]};if(action.type==='update_block')return {...current,blocks:[{...current.blocks[0],start_time:action.start_time??'08:00'}]};return current};"].join("\n") : "export {};", loader: "js" })); } }] });
const module = await import("data:text/javascript;base64," + Buffer.from(result.outputFiles[0].text).toString("base64"));
assert.deepEqual(Object.keys(module), ["n", "r", "t"]);
assert.equal(state.initialized, 1);
const initial = module.n();
assert.equal(initial.enabled, true);
assert.deepEqual(initial.blocks[0].days, ["mon", "tue", "wed", "thu", "fri", "sat", "sun"]);
assert.equal(initial.blocks[0].start_time, "00:00");
assert.equal(initial.blocks[0].end_time, "23:59");
assert.equal(module.t(initial, { type: "set_enabled", enabled: false }).enabled, false);
const added = module.t({ ...initial, enabled: false }, { type: "add_block" });
assert.equal(state.reducerCalls.at(-1).current.enabled, true);
assert.equal(added.blocks.at(-1).id, "added");
const updated = module.t(initial, { type: "update_block", start_time: "08:30" });
assert.equal(updated.enabled, true);
assert.equal(updated.blocks[0].start_time, "08:30");
assert.match(updated.blocks[0].id, /^web-study-hours-/);
assert.equal(updated.blocks[1], initial.blocks[0]);
assert.equal(module.t(initial, { type: "remove_block", id: initial.blocks[0].id }), initial);
const assertionCount = [...fs.readFileSync(fileURLToPath(import.meta.url), "utf8").matchAll(/\bassert\./g)].length;
console.log(assertionCount + " legacy study hours schedule assertions passed");
